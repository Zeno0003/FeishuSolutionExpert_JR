/**
 * 生成质检纸质单 Excel 模板（A4 竖版打印）
 * 用法: node scripts/gen-inspection-form.js
 */
const XLSX = require('xlsx');
const path = require('path');

const wb = XLSX.utils.book_new();

// ---------- 构建数据矩阵 ----------
const rows = [
  ['════════════════════════════════════════'],
  ['           📋 质检纸质单'],
  ['════════════════════════════════════════'],
  [''],
  ['采购短号:                         物流单号:'],
  ['供应商/货源:                      商品型号:'],
  ['成色:                             到货日期:'],
  [''],
  ['─────────────── 人员分配 ───────────────'],
  ['测试员:                           清洁员:'],
  ['复测人:                           复测件数:'],
  ['打磨员:'],
  [''],
  ['─────────────── 质检明细（按组件勾选） ───────────────'],
  ['组件           │ 良品数  │ 坏品数  │ 小计'],
  ['充电仓 (C)     │         │         │'],
  ['左耳   (L)     │         │         │'],
  ['右耳   (R)     │         │         │'],
  ['其他: ________ │         │         │'],
  [''],
  ['测试良品合计: ____________    测试坏品合计: ____________'],
  [''],
  ['─────────────── 坏品处理 ───────────────'],
  ['坏品处理方式:  [  ] 退回供应商    [  ] 留入主仓-待清洁'],
  ['坏品是否可退:  [  ] 是            [  ] 否'],
  ['坏品/成色问题退款金额: ____________'],
  ['备注: ______________________________________________'],
  ['       ______________________________________________'],
  [''],
  ['─────────────── 日期 ───────────────'],
  ['开单日期: ____________    完成日期: ____________'],
  ['采退日期: ____________'],
  [''],
  ['⚠️ 注: 良品表带要出库，手环9/10需拆表带后分开放，手环9要装盒。'],
  ['════════════════════════════════════════'],
];

// 转为 sheet
const ws = XLSX.utils.aoa_to_sheet(rows);

// ---------- 列宽 ----------
ws['!cols'] = [
  { wch: 55 },  // A 列宽
];

// ---------- 合并单元格 ----------
ws['!merges'] = [
  { s: { r: 0, c: 0 }, e: { r: 0, c: 0 } }, // ═══
  { s: { r: 1, c: 0 }, e: { r: 1, c: 0 } }, // 标题
  { s: { r: 2, c: 0 }, e: { r: 2, c: 0 } }, // ═══
  { s: { r: 21, c: 0 }, e: { r: 21, c: 0 } }, // 注
  { s: { r: 27, c: 0 }, e: { r: 27, c: 0 } }, // ═══
];

// ---------- 设置打印参数 ----------
ws['!pageSetup'] = {
  orientation: 'portrait',
  paperSize: 9,       // A4
  fitToPage: true,
  fitToWidth: 1,
  fitToHeight: 0,
  margins: {
    top: 0.5,
    bottom: 0.5,
    left: 0.5,
    right: 0.5,
    header: 0.3,
    footer: 0.3,
  },
};

XLSX.utils.book_append_sheet(wb, ws, '质检纸质单');

// ---------- 输出 ----------
const outPath = path.resolve(__dirname, '..', '_business', '质检纸质单模板.xlsx');
XLSX.writeFile(wb, outPath);
console.log('✅ 已生成:', outPath);
